export function shopItemArtSrc(item) {
  const uploaded = String(item?.image || item?.imageUrl || '').trim()
  if (uploaded) return uploaded
  const look = String(item?.look || '').trim()
  if (look && TANK_DECOR_ART[look]) return TANK_DECOR_ART[look]
  return ''
}
